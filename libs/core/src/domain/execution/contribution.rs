use capitainerie_common::RunId;

use super::{
    RepositoryRef,
    harness::{ANTIGRAVITY_MODELS, CLAUDE_CODE_MODELS, CODEX_MODELS, Harness, MISTRAL_VIBE_MODELS},
};

/// Where a change run writes the title and body of its contribution, outside
/// the checkout: the first line is the title, the rest the body.
pub const CONTRIBUTION_PATH: &str = "/workspace/.capitainerie/contribution.md";

/// GitHub refuses longer pull request titles.
pub const TITLE_MAX_CHARS: usize = 256;
pub const BODY_MAX_CHARS: usize = 20_000;

const BRANCH_SLUG_MAX_CHARS: usize = 40;
const BRANCH_SUFFIX_HEX: usize = 6;

const PLATFORM: &str = "capitainerie";

/// Words that tell a reader the text came from an AI tool or from the
/// platform's prompt, whatever the repository.
const ALWAYS_LEAKS: [&str; 18] = [
    "co-authored-by:",
    "generated with",
    "generated by ai",
    "as an ai",
    "ai assistant",
    "language model",
    "\u{1f916}",
    "codex cli",
    "input tokens",
    "output tokens",
    "tokens en entrée",
    "tokens en sortie",
    "<card>",
    "</card>",
    "<plan>",
    "/workspace/.capitainerie",
    "replies on the card",
    "a member approved the plan",
];

/// The title and body a run proposes for its commit and pull request.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Contribution {
    pub title: String,
    pub body: String,
}

impl Contribution {
    /// The first non-blank line, without a Markdown heading mark, is the
    /// title; the rest is the body. `None` without a title.
    pub fn parse(text: &str) -> Option<Self> {
        let text = text.trim_start();
        let (first, rest) = text.split_once('\n').unwrap_or((text, ""));
        let title = first.trim().trim_start_matches('#').trim();
        if title.is_empty() {
            return None;
        }
        Some(Self {
            title: cut(title, TITLE_MAX_CHARS),
            body: cut(rest.trim(), BODY_MAX_CHARS),
        })
    }

    /// The commit message: the title, a blank line, then the body.
    pub fn commit_message(&self) -> String {
        if self.body.is_empty() {
            self.title.clone()
        } else {
            format!("{}\n\n{}", self.title, self.body)
        }
    }
}

/// What may not leave the platform in a contribution: the models it runs,
/// its name and address, the identifiers of the run, and the marks of an AI
/// tool or of its prompt. Matched without case.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LeakGuard {
    terms: Vec<String>,
}

pub struct RunTraces<'a> {
    pub repository: &'a RepositoryRef,
    pub model: &'a str,
    pub console_url: Option<&'a str>,
    pub identifiers: &'a [uuid::Uuid],
}

impl LeakGuard {
    pub fn for_run(traces: &RunTraces<'_>) -> Self {
        let mut terms: Vec<String> = ALWAYS_LEAKS.iter().map(|term| (*term).to_owned()).collect();
        terms.extend(known_models().map(str::to_owned));
        terms.push(traces.model.to_owned());
        terms.extend(
            Harness::ALL
                .iter()
                .filter(|harness| **harness != Harness::Codex)
                .map(|harness| harness.name().to_owned()),
        );
        let repository = traces.repository.to_string().to_lowercase();
        if !repository.contains(PLATFORM) {
            terms.push(PLATFORM.to_owned());
        }
        if let Some(console) = traces.console_url.and_then(host_of) {
            terms.push(console);
        }
        for id in traces.identifiers {
            terms.push(id.hyphenated().to_string());
            terms.push(id.simple().to_string());
        }
        let mut terms: Vec<String> = terms
            .into_iter()
            .map(|term| term.trim().to_lowercase())
            .filter(|term| !term.is_empty())
            .collect();
        terms.sort();
        terms.dedup();
        Self { terms }
    }

    /// One term per line, for the task's script to check the commit with.
    pub fn as_lines(&self) -> String {
        self.terms.join("\n")
    }

    /// The terms the text contains.
    pub fn found_in(&self, text: &str) -> Vec<&str> {
        let text = text.to_lowercase();
        self.terms
            .iter()
            .filter(|term| text.contains(term.as_str()))
            .map(String::as_str)
            .collect()
    }

    pub fn passes(&self, text: &str) -> bool {
        self.found_in(text).is_empty()
    }
}

fn known_models() -> impl Iterator<Item = &'static str> {
    CLAUDE_CODE_MODELS
        .into_iter()
        .chain(CODEX_MODELS)
        .chain(
            ANTIGRAVITY_MODELS
                .into_iter()
                .flat_map(|(id, upstream)| [id, upstream]),
        )
        .chain(
            MISTRAL_VIBE_MODELS
                .into_iter()
                .flat_map(|(id, upstream)| [id, upstream]),
        )
}

fn host_of(url: &str) -> Option<String> {
    let rest = url.split_once("://").map_or(url, |(_, rest)| rest);
    let host = rest.split(['/', '?', '#']).next()?.trim();
    (!host.is_empty()).then(|| host.to_owned())
}

/// The text a contribution falls back on when the run's own is missing or
/// leaks: the card's title when it passes, a plain one otherwise.
pub fn fallback_contribution(guard: &LeakGuard, card_title: &str) -> Contribution {
    let title = card_title.split_whitespace().collect::<Vec<_>>().join(" ");
    let title = if title.is_empty() || !guard.passes(&title) {
        "Apply the requested change".to_owned()
    } else {
        cut(&title, TITLE_MAX_CHARS)
    };
    Contribution {
        title,
        body: String::new(),
    }
}

/// The branch a change run pushes to: `change/<slug of the card title>-<6 hex
/// of the run id>`. The head of a UUIDv7 is a timestamp, so the hex comes
/// from its random tail.
pub fn change_branch(card_title: &str, run_id: RunId, guard: &LeakGuard) -> String {
    let simple = run_id.0.simple().to_string();
    let suffix = &simple[simple.len() - BRANCH_SUFFIX_HEX..];
    let slug = slug(card_title);
    let slug = if slug.is_empty() || !guard.passes(&slug) {
        "update".to_owned()
    } else {
        slug
    };
    format!("change/{slug}-{suffix}")
}

fn slug(text: &str) -> String {
    let mut slug = String::new();
    for c in text.chars().map(fold_accent) {
        if c.is_ascii_alphanumeric() {
            slug.push(c.to_ascii_lowercase());
        } else if !slug.ends_with('-') && !slug.is_empty() {
            slug.push('-');
        }
        if slug.len() >= BRANCH_SLUG_MAX_CHARS {
            break;
        }
    }
    slug.trim_end_matches('-').to_owned()
}

fn fold_accent(c: char) -> char {
    match c {
        'à' | 'á' | 'â' | 'ä' | 'ã' | 'å' | 'À' | 'Á' | 'Â' | 'Ä' | 'Ã' | 'Å' => 'a',
        'é' | 'è' | 'ê' | 'ë' | 'É' | 'È' | 'Ê' | 'Ë' => 'e',
        'í' | 'ì' | 'î' | 'ï' | 'Í' | 'Ì' | 'Î' | 'Ï' => 'i',
        'ó' | 'ò' | 'ô' | 'ö' | 'õ' | 'Ó' | 'Ò' | 'Ô' | 'Ö' | 'Õ' => 'o',
        'ú' | 'ù' | 'û' | 'ü' | 'Ú' | 'Ù' | 'Û' | 'Ü' => 'u',
        'ç' | 'Ç' => 'c',
        'ñ' | 'Ñ' => 'n',
        'ÿ' | 'Ÿ' => 'y',
        other => other,
    }
}

fn cut(text: &str, max: usize) -> String {
    text.chars().take(max).collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::domain::execution::valid_branch_name;

    fn guard() -> LeakGuard {
        let repository: RepositoryRef = "Hypolia/lobby".parse().unwrap();
        LeakGuard::for_run(&RunTraces {
            repository: &repository,
            model: "mistral-large-4-0",
            console_url: Some("https://console.example.test/app"),
            identifiers: &[uuid::Uuid::parse_str("0a1b2c3d-0000-7000-8000-0123456789ab").unwrap()],
        })
    }

    #[test]
    fn the_first_line_is_the_title_and_the_rest_the_body() {
        let parsed =
            Contribution::parse("\n# feat(lobby): keep two games\n\nRemoves the others.\n")
                .unwrap();
        assert_eq!(parsed.title, "feat(lobby): keep two games");
        assert_eq!(parsed.body, "Removes the others.");
        assert_eq!(
            parsed.commit_message(),
            "feat(lobby): keep two games\n\nRemoves the others."
        );
    }

    #[test]
    fn a_text_without_a_title_is_no_contribution() {
        assert_eq!(Contribution::parse("  \n\n"), None);
        assert_eq!(Contribution::parse("#\nbody"), None);
    }

    #[test]
    fn a_title_alone_is_its_own_commit_message() {
        let parsed = Contribution::parse("fix: typo").unwrap();
        assert_eq!(parsed.body, "");
        assert_eq!(parsed.commit_message(), "fix: typo");
    }

    #[test]
    fn models_the_platform_and_the_run_ids_are_leaks() {
        let guard = guard();
        for leak in [
            "Done with Mistral-Large-4-0",
            "Powered by claude-opus-5-5",
            "see https://console.example.test/kanban",
            "Card 0a1b2c3d-0000-7000-8000-0123456789ab",
            "run 0a1b2c3d0000700080000123456789ab",
            "Opened by Capitainerie",
            "Co-Authored-By: someone",
            "\u{1f916} Generated with a tool",
            "1200 input tokens",
            "As an AI, I removed it",
            "Per the <card> block",
            "Written with Mistral Vibe",
        ] {
            assert!(!guard.passes(leak), "{leak}");
        }
    }

    #[test]
    fn an_ordinary_contribution_passes() {
        let guard = guard();
        assert!(guard.passes(
            "feat(lobby): keep only Sheepwars and Towerwars\n\nRemoves the Pitchout, PvPSwap and Moutron entries from the menu and their pedestals."
        ));
    }

    #[test]
    fn the_platform_name_is_allowed_in_its_own_repositories() {
        let repository: RepositoryRef = "ferrislabs/capitainerie".parse().unwrap();
        let guard = LeakGuard::for_run(&RunTraces {
            repository: &repository,
            model: "claude-opus-5-5",
            console_url: None,
            identifiers: &[],
        });
        assert!(guard.passes("fix(capitainerie-api): reject empty titles"));
        assert!(!guard.passes("fix: use claude-opus-5-5"));
    }

    #[test]
    fn the_terms_reach_the_script_one_per_line_in_lower_case() {
        let lines = guard().as_lines();
        assert!(lines.lines().any(|line| line == "capitainerie"));
        assert!(lines.lines().any(|line| line == "console.example.test"));
        assert!(lines.lines().any(|line| line == "mistral vibe"));
        assert!(lines.lines().all(|line| line == line.to_lowercase()));
    }

    #[test]
    fn the_fallback_is_the_card_title_unless_it_leaks() {
        let guard = guard();
        assert_eq!(
            fallback_contribution(&guard, "  Retirer   les mini-jeux ").title,
            "Retirer les mini-jeux"
        );
        assert_eq!(
            fallback_contribution(&guard, "Brancher Capitainerie").title,
            "Apply the requested change"
        );
    }

    #[test]
    fn a_change_branch_names_the_card_and_ends_with_the_run_tail() {
        let run_id = RunId(uuid::Uuid::parse_str("0a1b2c3d-0000-7000-8000-0123456789ab").unwrap());
        let branch = change_branch(
            "Retirer les mini-jeux sauf Sheepwars & Towerwars !",
            run_id,
            &guard(),
        );
        assert_eq!(
            branch,
            "change/retirer-les-mini-jeux-sauf-sheepwars-tow-6789ab"
        );
        assert!(valid_branch_name(&branch));
        assert_eq!(
            change_branch("Éditer l'été", run_id, &guard()),
            "change/editer-l-ete-6789ab"
        );
        assert_eq!(
            change_branch("!!!", run_id, &guard()),
            "change/update-6789ab"
        );
        assert_eq!(
            change_branch("Brancher Capitainerie", run_id, &guard()),
            "change/update-6789ab"
        );
    }
}
